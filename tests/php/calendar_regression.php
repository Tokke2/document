<?php
declare(strict_types=1);
require_once __DIR__ . '/../../functions.php';
require_once __DIR__ . '/../../includes/calendar.php';
$n = 0;
$assert = static function (bool $ok, string $message) use (&$n): void { $n++; if (!$ok) throw new RuntimeException($message); };
$a = str_repeat('a', 32); $b = str_repeat('b', 32); $c = str_repeat('c', 32);
$post = ['event_id'=>'', 'title'=>'Private work', 'notes'=>'Next step', 'date'=>'2026-11-18', 'start_time'=>'08:00', 'end_time'=>'09:00', 'status'=>'planned', 'owner_id'=>$b, 'shared_with'=>[]];
$create = portal_calendar_apply([], $a, 'save', $post, [$a,$b,$c]);
$assert($create['ok'] && $create['records'][0]['owner_id'] === $a, 'Actor owns event regardless of submitted owner');
$records = $create['records']; $id = $records[0]['id'];
$assert(count(portal_calendar_visible($records, $a)) === 1 && portal_calendar_visible($records, $b) === [], 'Private event not visible to another account');
$assert(portal_calendar_visible($records, 'central-admin') === [], 'Central admin is not a personal identity');
$post['event_id'] = $id; $post['revision'] = '1'; $post['shared_with'] = [$b];
$shared = portal_calendar_apply($records, $a, 'save', $post, [$a,$b,$c]);
$assert($shared['ok'] && count(portal_calendar_visible($shared['records'], $b)) === 1 && portal_calendar_visible($shared['records'], $c) === [], 'Only explicit recipient sees shared event');
$post['revision'] = '2';
$assert(!portal_calendar_apply($shared['records'], $b, 'save', $post, [$a,$b,$c])['ok'], 'Recipient cannot edit');
$assert(!portal_calendar_apply($shared['records'], $b, 'delete', $post, [$a,$b,$c])['ok'], 'Recipient cannot delete');
$assert(!portal_calendar_apply($shared['records'], 'central-admin', 'save', $post, [$a,$b,$c])['ok'], 'Shared admin identity cannot modify');
$post['shared_with'] = [$c, '../bad'];
$assert(!portal_calendar_apply($shared['records'], $a, 'save', $post, [$a,$b,$c])['ok'], 'Invalid recipient fails closed');
$post['shared_with'] = [$c];
$assert(!portal_calendar_apply($shared['records'], $a, 'save', $post, [$a,$b])['ok'], 'Inactive or unknown recipient rejected');
$post['shared_with'] = [];
$revoked = portal_calendar_apply($shared['records'], $a, 'save', $post, [$a,$b,$c]);
$assert($revoked['ok'] && portal_calendar_visible($revoked['records'], $b) === [], 'Revocation removes visibility');
$assert(!portal_calendar_apply($revoked['records'], $a, 'delete', $post, [$a,$b,$c])['ok'], 'Stale revision rejected');
$post['revision'] = '3';
$assert(portal_calendar_apply($revoked['records'], $a, 'delete', $post, [$a,$b,$c])['records'] === [], 'Owner can delete current revision');
$post['event_id'] = ''; $post['date'] = '2026-02-30';
$assert(!portal_calendar_apply([], $a, 'save', $post, [$a])['ok'], 'Invalid date rejected');
echo "PASS: $n calendar access and validation checks.\n";
