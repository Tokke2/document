'use strict';
const assert = require('node:assert/strict');
const { execFileSync } = require('node:child_process');
const { JSDOM } = require('jsdom');
const voice = require('../assets/invoice_voice.js');
const output = execFileSync('npx', ['--yes', '@php-wasm/cli', '-r', 'require "tests/php/invoice_assistance_render_regression.php"; $GLOBALS["TEST_VOICE_PERSONAL"]=true; echo "VOICE_HTML:".base64_encode(render_invoice(true,false,[],"sv"));'], { encoding: 'utf8' });
const html = Buffer.from(output.split('VOICE_HTML:')[1], 'base64').toString('utf8');
const flush = () => new Promise(resolve => setImmediate(resolve));
(async () => {
    const dom = new JSDOM(html, { url: 'https://example.test/?tab=invoice', runScripts: 'outside-only', pretendToBeVisual: true });
    const win = dom.window;
    let current, failLoad = false, failSync = false, blockSync = false, releaseSync, blockTrack = false, releaseTrack;
    const profile = { learning: true, auto: false, reviewed: 49, corrections: [], share_learning:false,numeric_learning: false, numeric_corrections: [] };
    const requests = [];
    const tokenData = new Map(); let nextToken = 0;
    const issueToken = data => { const token = 'a'.repeat(32) + '.T' + (++nextToken); tokenData.set(token, data); return token; };
    class Recognition { constructor() { current = this; } start() {} stop() { this.onend(); } abort() { this.onend(); } }
    win.matchMedia = () => ({ matches: false, addListener() {}, removeListener() {}, addEventListener() {} });
    win.confirm = () => true;
    win.SpeechRecognition = Recognition;
    win.InvoiceVoice = voice;
    win.fetch = async (_url, options) => {
        const p = options && options.body;
        if (!p || p.get('action') !== 'voice_learning') return { ok: true, json: async () => ({ ok: true }) };
        const op = p.get('operation'); requests.push({ op, keys: Array.from(p.keys()) });
        if (op === 'sync_auto' && blockSync) { blockSync = false; await new Promise(resolve => { releaseSync = resolve; }); }
        if (op === 'sync_auto' && failSync) return { ok: false, json: async () => ({code:'storage_error'}) };
        if (op === 'track_auto' && blockTrack) { blockTrack = false; await new Promise(resolve => { releaseTrack = resolve; }); }
        if (op === 'track_auto' && failLoad) return { ok: false, json: async () => ({code:'storage_error'}) };
        if (op === 'review') { profile.reviewed = Math.min(50, profile.reviewed + 1); if (p.get('heard') && p.get('heard') !== p.get('approved')) profile.corrections.push({ heard: p.get('heard'), approved: p.get('approved') }); }
        if (op === 'auto_on') profile.auto = true;
        if (op === 'share_on') profile.share_learning = true;
        if (op === 'share_off') profile.share_learning = false;
        if (op === 'correction') { profile.corrections = profile.corrections.filter(x => x.heard !== p.get('heard')); if (p.get('heard') !== p.get('approved')) profile.corrections.push({ heard: p.get('heard'), approved: p.get('approved') }); }
        let token;
        if (op === 'track_auto') token = issueToken({ heard: p.get('heard'), baseline: p.get('approved') });
        if (op === 'sync_auto') {
            const entry = tokenData.get(p.get('voice_token'));
            if (!entry) return { ok: false, json: async () => ({ code:'invalid_token' }) };
            const approved = p.get('approved');
            if (approved !== entry.baseline) {
                profile.corrections = profile.corrections.filter(x => x.heard !== entry.heard);
                if (approved !== entry.heard) profile.corrections.push({ heard: entry.heard, approved });
                token = issueToken({ heard: entry.heard, baseline: approved });
            } else token = p.get('voice_token');
        }
        return { ok: true, json: async () => ({ ok: true, profile: structuredClone(profile), token }) };
    };
    for (const script of win.document.querySelectorAll('script:not([src])')) win.eval(script.textContent);
    const get = s => win.document.querySelector(s);
    const say = async text => {
        get('#voice-start').click();
        const item = [{ transcript: text }]; item.isFinal = true;
        current.onresult({ results: [item] }); current.onend(); await flush(); await flush();
    };
    await flush();
    const share = get('#voice-share-toggle');
    assert.equal(share.disabled, false);
    win.confirm = () => false; share.click(); await flush();
    assert.equal(requests.filter(r => r.op === 'share_on').length, 0, 'Cancel prevents opt-in');
    win.confirm = () => true; share.click(); await flush(); await flush();
    assert.equal(profile.share_learning, true, 'Explicit consent enables sharing');
    assert.match(share.textContent, /Sluta dela/);
    share.click(); await flush(); await flush();
    assert.equal(profile.share_learning, false, 'Sharing can be stopped independently');
    assert.equal(get('#voice-auto-toggle').disabled, true, 'Automatic entry is disabled at 49 reviews');
    await say('2st Glasreparationer 750 kr st');
    assert.equal(get('.invoice-item-name').value, '', 'Before 50, speech is only a suggestion');
    get('#voice-apply').click(); await flush();
    assert.equal(profile.reviewed, 50, 'Manual voice approval counts');
    assert.equal(get('#voice-auto-toggle').disabled, false);
    get('#voice-auto-toggle').click(); await flush();
    assert.equal(profile.auto, true, 'Automatic mode needs opt-in');
    await say('1st Sten skott 450 kr st färdigt');
    let rows = win.document.querySelectorAll('.invoice-item-name');
    assert.equal(rows.length, 2); assert.equal(rows[1].value, 'Sten skott', 'Complete new speech is applied automatically');
    assert.equal(profile.reviewed, 50, 'Automatic entries never count as verified reviews');
    rows[1].value = 'Stenskott'; rows[1].dispatchEvent(new win.Event('change', { bubbles: true })); await flush();
    assert.deepEqual(profile.corrections, [{ heard: 'Sten skott', approved: 'Stenskott' }], 'Later correction to automatic row teaches the description');
    await say('3st Sten skott 600 kr st');
    rows = win.document.querySelectorAll('.invoice-item-name');
    assert.equal(rows.length, 2, 'Personal corrections never apply automatically');
    assert.equal(get('#voice-article-choices').hidden, false);
    assert.match(get('#voice-article-options').textContent, /Stenskott/);
    get('#voice-article-options button').click(); get('#voice-apply').click(); await flush();
    rows = win.document.querySelectorAll('.invoice-item-name');
    assert.equal(rows[2].value, 'Stenskott', 'Explicitly selected correction is used');
    assert.equal(win.document.querySelectorAll('.invoice-item-price')[2].value, '600', 'Prices come from the current speech, not stored learning');
    const allowedKeys = ['action','operation','csrf_token','heard','approved','observation_id','voice_token'];
    assert(requests.every(r => r.keys.every(k => allowedKeys.includes(k))), 'Only descriptions, observation ID and required controls are transmitted');
    await say('2st Glasreparationer 750 kr st');
    assert.equal(win.document.querySelectorAll('.invoice-item-name').length, 3, 'Auto detects duplicates anywhere in the invoice, not only the latest');
    assert.match(get('#voice-status').textContent, /dubblett/);
    get('#voice-clear').click();
    rows[0].focus(); await say('1st Annan 900 kr st');
    assert.equal(rows[0].value, 'Glasreparationer', 'Auto never overwrites a selected non-empty row');
    assert.match(get('#voice-status').textContent, /manuellt/);
    get('#voice-clear').click();
    get('#voice-destination').value = 'auto'; get('#voice-destination').dispatchEvent(new win.Event('change', { bubbles: true }));
    failLoad = true; await say('1st Extra 900 kr st');
    assert.equal(win.document.querySelectorAll('.invoice-item-name').length, 3, 'Storage/network failure prevents automatic entry');
    assert.match(get('#voice-status').textContent, /manuellt/);
    failLoad = false;
    get('#voice-learning-retry').click(); await flush(); await flush();
    // Refresh the personal profile after the intentionally failed request.
    get('#voice-start').click();
    const blockedItem = [{ transcript: '1st Kundskydd 910 kr st' }]; blockedItem.isFinal = true;
    blockTrack = true;
    current.onresult({ results: [blockedItem] }); current.onend(); await flush();
    assert.equal(typeof releaseTrack, 'function', 'Auto verification is in flight');
    get('#invoice-customer').value = 'Ny kund';
    get('#invoice-customer').dispatchEvent(new win.Event('input', { bubbles: true }));
    releaseTrack(); await flush(); await flush();
    assert.equal(win.document.querySelectorAll('.invoice-item-name').length, 3, 'A late automatic response cannot write to a different customer');
    get('#voice-apply').click();
    assert.equal(win.document.querySelectorAll('.invoice-item-name').length, 3, 'Manual apply also requires reinterpretation after customer change');
    const savedToken = rows[1].closest('tr').querySelector('.invoice-voice-token').value;
    dom.window.close();
    const restored = new JSDOM(html, { url: 'https://example.test/?tab=invoice', runScripts: 'outside-only', pretendToBeVisual: true });
    const restoredWin = restored.window;
    restoredWin.matchMedia = win.matchMedia; restoredWin.fetch = win.fetch; restoredWin.confirm = () => true;
    restoredWin.SpeechRecognition = Recognition; restoredWin.InvoiceVoice = voice;
    const restoredName = restoredWin.document.querySelector('.invoice-item-name');
    restoredName.value = 'Stenskott';
    restoredWin.document.querySelector('.invoice-voice-token').value = savedToken;
    profile.auto = false; failLoad = false;
    for (const script of restoredWin.document.querySelectorAll('script:not([src])')) restoredWin.eval(script.textContent);
    await flush(); await flush();
    restoredName.value = 'Lagning av stenskott';
    restoredName.dispatchEvent(new restoredWin.Event('change', { bubbles: true }));
    await flush(); await flush();
    assert.deepEqual(profile.corrections, [{ heard: 'Sten skott', approved: 'Lagning av stenskott' }], 'A later correction after reopening continues learning even with auto off');
    assert.equal(profile.reviewed, 50, 'Corrections to old automatic rows do not count as reviewed dictations');
    blockSync = true;
    restoredName.value = 'Tillfälligt fel'; restoredName.dispatchEvent(new restoredWin.Event('change', { bubbles: true }));
    await flush();
    restoredName.value = 'Sten skott'; restoredName.dispatchEvent(new restoredWin.Event('change', { bubbles: true }));
    releaseSync(); await flush(); await flush(); await flush();
    assert.deepEqual(profile.corrections, [], 'A fast edit back to the original does not leave a stale correction');
    failSync = true;
    restoredName.value = 'Stenskottslagning'; restoredName.dispatchEvent(new restoredWin.Event('change', { bubbles: true }));
    await flush(); await flush();
    assert.equal(restoredWin.document.querySelector('#voice-learning-retry').hidden, false, 'Failed correction sync is visible and retryable');
    failSync = false;
    restoredWin.document.querySelector('#voice-learning-retry').click();
    await flush(); await flush(); await flush();
    assert.deepEqual(profile.corrections, [{ heard: 'Sten skott', approved: 'Stenskottslagning' }], 'Retry synchronizes a previously failed correction');
    const foreign = restoredWin.document.querySelector('.invoice-voice-token');
    foreign.value = 'b'.repeat(32) + '.foreign';
    restoredName.value = 'Annan persons ändring'; restoredName.dispatchEvent(new restoredWin.Event('input', { bubbles: true }));
    assert.equal(foreign.value, '', 'Changing someone else’s row detaches their private learning link');
    restored.window.close();
    console.log('PASS: personal voice learning and automatic-entry simulated DOM checks.');
})().catch(error => { console.error(error); process.exitCode = 1; });
