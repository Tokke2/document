'use strict';
// Real rendered forms and production JS, simulated browser/microphone APIs.
const assert = require('node:assert/strict');
const { execFileSync } = require('node:child_process');
const { JSDOM, VirtualConsole } = require('jsdom');
const voice = require('../assets/invoice_voice.js');
const php = `require "tests/php/invoice_assistance_render_regression.php";
$GLOBALS['TEST_CATALOG']=[['id'=>str_repeat('b',32),'name'=>'Glasbyte','unit'=>'st','price'=>750,'fixed_price'=>true]];
$GLOBALS['TEST_INVOICES']=[['id'=>'workflow','customer'=>'Alice','date'=>'2026-01-03','items'=>[
['art'=>'Glasbyte','qty'=>'2','unit'=>'st','price'=>'750','fixed_lock'=>str_repeat('c',32),'voice_token'=>str_repeat('a',32).'.opaqueToken'],
['art'=>'Arbete','qty'=>'1','unit'=>'tim','price'=>'500']]]];
$out=[]; foreach ([false,true] as $scoped) foreach (['sv','en'] as $lang) $out[]=render_invoice(false,$scoped,['edit_id'=>'workflow'],$lang);
echo 'WORKFLOW_HTML:'.base64_encode(json_encode($out));`;
const raw = execFileSync('npx', ['--yes', '@php-wasm/cli', '-r', php], { encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 });
const forms = JSON.parse(Buffer.from(raw.split('WORKFLOW_HTML:')[1], 'base64').toString());
const final = text => { const item = [{ transcript: text }]; item.isFinal = true; return item; };
for (const [i, html] of forms.entries()) {
    const errors = [], vc = new VirtualConsole(); vc.on('jsdomError', e => errors.push(e));
    const dom = new JSDOM(html, { url: 'https://example.test/pwa-underlag.php', runScripts: 'outside-only', virtualConsole: vc, pretendToBeVisual: true });
    const w = dom.window, d = w.document, get = s => d.querySelector(s);
    let engine, timeout;
    const nativeTimeout = w.setTimeout.bind(w);
    w.setTimeout = (callback, ms, ...args) => ms === 60000 ? (timeout = callback, 999999) : nativeTimeout(callback, ms, ...args);
    class Recognition { constructor() { engine = this; this.aborted = 0; } start() {} abort() { this.aborted++; if (this.onend) this.onend(); } stop() { if (this.onend) this.onend(); } }
    w.SpeechRecognition = Recognition; w.InvoiceVoice = voice; w.confirm = () => true;
    w.matchMedia = () => ({ matches: false, addEventListener() {}, addListener() {} });
    w.fetch = async () => ({ ok: true, json: async () => ({ ok: true }) });
    for (const script of d.querySelectorAll('script:not([src])')) w.eval(script.textContent);
    const body = get('#invoice-items tbody') || get('.invoice-table tbody');
    assert.ok(body, 'Invoice rows exist');
    const fixed = body.rows[0], work = body.rows[1];
    assert.equal(fixed.querySelector('[data-move-line="up"]').disabled, true);
    work.querySelector('[data-move-line="up"]').click();
    assert.equal(body.rows[0], work, 'Moves real row, not just displayed values');
    assert.equal(fixed.querySelector('.invoice-fixed-lock').value, 'c'.repeat(32));
    assert.equal(fixed.querySelector('.invoice-voice-token').value, 'a'.repeat(32) + '.opaqueToken');
    assert.equal(fixed.querySelector('.invoice-item-price').readOnly, true);
    assert.equal(fixed.querySelector('.invoice-item-unit').disabled, true);
    let data = new w.FormData(get('#invoice-form'));
    assert.equal(data.get('items[0][art]'), 'Arbete');
    assert.equal(data.get('items[1][unit]'), 'st', 'Disabled fixed unit keeps its posted mirror');
    assert.equal(data.get('items[1][fixed_lock]'), 'c'.repeat(32));
    work.querySelector('[data-move-line="down"]').click();
    assert.equal(body.rows[0], fixed);
    const unit = work.querySelector('.invoice-item-unit'); unit.value = 'st';
    unit.dispatchEvent(new w.Event('change', { bubbles: true }));
    assert.equal(work.querySelector('.invoice-quantity-unit').textContent, 'st');
    assert.equal(work.querySelector('.invoice-item-qty').nextElementSibling.className, 'invoice-quantity-unit');
    const more = get('#invoice-more-fields'); assert.equal(more.open, false);
    assert.equal(get('#invoice-customer').closest('details'), null, 'Customer stays visible');
    assert.equal(get('#invoice-date').closest('details'), null, 'Record date stays visible');
    assert.equal(get('#invoice-reference').closest('details'), more);
    get('#invoice-delivery-date').value = '2026-02-03';
    get('#invoice-delivery-date').dispatchEvent(new w.Event('invalid', { cancelable: true }));
    assert.equal(more.open, true, 'Invalid optional field is revealed');
    more.open = false; w.dispatchEvent(new w.Event('beforeprint')); assert.equal(more.open, true);
    w.dispatchEvent(new w.Event('afterprint')); assert.equal(more.open, false);
    assert.equal(new w.FormData(get('#invoice-form')).get('i[delivery_date]'), '2026-02-03', 'Collapsed values are still posted');
    get('#voice-start').click(); const first = engine;
    assert.equal(first.interimResults, true);
    const interim = [{ transcript: 'Arbete två timmar' }]; interim.isFinal = false;
    first.onresult({ results: [interim], resultIndex: 0 });
    assert.equal(get('#voice-heard').hidden, false);
    assert.match(get('#voice-heard').textContent, /Arbete två timmar/);
    assert.equal(get('#voice-transcript').value, '', 'Interim speech never changes the proposal or invoice');
    get('#invoice-customer').value = 'Bob'; get('#invoice-customer').dispatchEvent(new w.Event('input', { bubbles: true }));
    assert.equal(first.aborted, 1); assert.equal(get('#voice-start').disabled, false);
    assert.equal(get('#voice-heard').hidden, true);
    first.onresult({ results: [final('Arbete två timmar 900 kronor')], resultIndex: 0 }); first.onend();
    assert.equal(get('#voice-transcript').value, '', 'Late speech from prior customer is ignored');
    get('#voice-start').click(); const selected = engine;
    get('#invoice-customer-select').value = 'customer1'; get('#invoice-customer-select').dispatchEvent(new w.Event('change', { bubbles: true }));
    assert.equal(selected.aborted, 1, 'Selecting from customer register also aborts');
    get('#voice-start').click(); const network = engine; network.onerror({ error: 'network' });
    assert.equal(get('#voice-start').disabled, false, 'Failed recognition can be restarted without onend');
    assert.match(get('#voice-status').textContent, i % 2 ? /connection/ : /anslutningen/);
    get('#voice-start').click(); const timed = engine; timeout(); assert.equal(timed.aborted, 1);
    get('#voice-start').click(); const success = engine;
    success.onresult({ results: [final('Arbete två timmar 500 kronor')], resultIndex: 0 }); success.onend();
    assert.equal(get('#voice-transcript').value, 'Arbete två timmar 500 kronor');
    assert.equal(body.rows.length, 2, 'Speech stays a proposal without explicit use');
    get('#voice-start').click(); const hidden = engine;
    Object.defineProperty(d, 'hidden', { value: true, configurable: true }); d.dispatchEvent(new w.Event('visibilitychange'));
    assert.equal(hidden.aborted, 1, 'Backgrounding page releases microphone');
    assert.deepEqual(errors, []);
    dom.window.close();
}
console.log('PASS: row reorder with locks/provenance and submitted order, quantity units, optional fields/print, live speech, customer-change/late-result protection, errors, timeout and background pause (portal/PWA, Swedish/English).');
