'use strict';
const assert=require('node:assert/strict');
const {execFileSync}=require('node:child_process');
const {JSDOM}=require('jsdom');
const php='ob_start(); require "tests/php/admin_panel_render_regression.php"; ob_end_clean(); echo base64_encode($active);';
const encoded=execFileSync('npx',['--yes','@php-wasm/cli','-r',php],{encoding:'utf8'}).trim();
const document=new JSDOM(Buffer.from(encoded,'base64').toString('utf8')).window.document;
const forms=document.querySelectorAll('.central-admin-release-one-click');
assert.equal(forms.length,1);
const form=forms[0];
assert.equal(form.method.toLowerCase(),'post');
assert.equal(form.getAttribute('action'),'?tab=admin');
assert.equal(form.parentElement.closest('form'),null,'The update form is not nested in another form');
const data=new document.defaultView.FormData(form);
assert.equal(data.get('action'),'portal_release_install_latest');
assert.ok(data.get('csrf_token'));
assert.equal(data.has('confirm_install'),false);
assert.ok(form.querySelector('button[type="submit"]').textContent.includes('Uppdatera till senaste release'));
assert.ok(document.querySelector('.central-admin-release').textContent.includes('utan att först visa en fillista'));
assert.ok(document.querySelector('style').textContent.includes('p.central-admin-release-note { display:block'));
console.log('PASS: single-submit update form, CSRF and release warning layout.');
