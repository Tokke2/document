'use strict';
const assert=require('node:assert/strict');
const {execFileSync}=require('node:child_process');
const {JSDOM}=require('jsdom');
const php='ob_start(); require "tests/php/admin_panel_render_regression.php"; ob_end_clean(); echo base64_encode($review);';
const encoded=execFileSync('npx',['--yes','@php-wasm/cli','-r',php],{encoding:'utf8'}).trim();
const document=new JSDOM(Buffer.from(encoded,'base64').toString('utf8')).window.document;
const form=document.querySelector('.central-admin-release-approval');
const checkbox=document.querySelector('#release-confirm-install');
assert.ok(form && checkbox && checkbox.required && !checkbox.checked);
assert.equal(document.querySelector('label[for="release-confirm-install"]').control,checkbox);
assert.equal(form.checkValidity(),false);
checkbox.checked=true;
assert.equal(form.checkValidity(),true);
const data=new document.defaultView.FormData(form);
assert.equal(data.get('action'),'portal_release_install');
assert.equal(data.get('confirm_install'),'1');
assert.ok(data.get('csrf_token'));
assert.ok(form.textContent.includes('1. Kryssa i bekräftelserutan'));
assert.ok(form.textContent.includes('2. Tryck sedan på knappen en gång'));
console.log('PASS: explicit release confirmation and single-submit form DOM checks.');
