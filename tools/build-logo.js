'use strict';
// Regenerate assets/tadega-logo.svg (outlined wordmark for screen) and
// assets/tadega-logo-tryck.svg (editable print original with live text).
// The badge comes from assets/tadega-icon.svg; "Dokumentportalen" and "TADGA AB" are
// converted to outlines with opentype.js in the screen logo so print output
// can never substitute a font, while the print SVG keeps them as text objects.
// Run: node tools/build-logo.js
const fs = require('node:fs');
const path = require('node:path');
const opentype = require('opentype.js');

const root = path.resolve(__dirname, '..');
const fontPath = path.join(
    root,
    'node_modules/@expo-google-fonts/inter/800ExtraBold/Inter_800ExtraBold.ttf'
);
const font = (() => {
    const buffer = fs.readFileSync(fontPath);
    return opentype.parse(buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength));
})();

const scaleOf = (fontSize) => fontSize / font.unitsPerEm;

/** Lay a string out glyph by glyph (with kerning and optional tracking). */
function outline(text, fontSize, x, y, tracking = 0) {
    const scale = scaleOf(fontSize);
    let penX = x;
    let pathData = '';
    let previous = null;
    for (const character of text) {
        const glyph = font.charToGlyph(character);
        if (previous) {
            penX += font.getKerningValue(previous, glyph) * scale;
        }
        pathData += glyph.getPath(penX, y, fontSize).toPathData(2);
        penX += glyph.advanceWidth * scale + tracking;
        previous = glyph;
    }
    return { pathData, advance: Math.round(penX - x - tracking) };
}

const title = outline('Dokumentportalen', 64, 272, 150);
if (272 + title.advance > 960) {
    throw new Error(`Wordmark overflows the viewBox (ends at ${272 + title.advance})`);
}
const subtitle = outline('TADGA AB', 24, 274, 200, 7);

// Single source of truth: use the exact same windshield + lightning as the
// PWA icons, favicon and PDF raster. Never maintain a second drawing here.
const icon = fs.readFileSync(path.join(root, 'assets/tadega-icon.svg'), 'utf8');
const iconPaths = icon.replace(/^<svg\b[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 240" role="img" aria-label="Tadega AB – Dokumentportalen">
  <!--
    Editable vector logo for screen and print, generated by tools/build-logo.js.
    The wordmark is outlined paths (Inter ExtraBold) so no font is required
    at the print shop; edit wording/type only by rerunning the build script.
  -->
  <!-- Flat fills only: portal_sanitize_svg strips defs/gradients on view. -->
  <g transform="translate(0 0) scale(0.46875)">${iconPaths}
  </g>
  <path d="${title.pathData}" fill="#0b2239"/>
  <path d="${subtitle.pathData}" fill="#0f9b8e"/>
</svg>
`;

const target = path.join(root, 'assets/tadega-logo.svg');
fs.writeFileSync(target, svg);
console.log(`assets/tadega-logo.svg written (wordmark ${title.advance}px, subtitle ${subtitle.advance}px)`);

// Print original: same badge, but the wordmark stays live text so anyone can
// edit names and colours directly in Illustrator/Inkscape before printing.
const printSvg = `<svg xmlns="http://www.w3.org/2000/svg" width="100mm" height="24mm" viewBox="0 0 1000 240" role="img" aria-label="Tadega AB – Dokumentportalen">
  <!--
    Tadega AB – redigerbar logotyp för tryck (vektorbaserad originalfil).
    Palett: #07172d mörkblå, #ffffff vit, #7fd6c8 turkos, #0f9b8e djup turkos,
    #0b2239 ordmärke.
    Ikonen är rena vektorbanor och kan skalas fritt utan kvalitetsförlust.
    Ordmärket är textobjekt (Inter ExtraBold): öppna filen i Illustrator eller
    Inkscape och redigera namn och färger direkt. Inför tryck: konvertera
    texten till banor (Illustrator: Text → Skapa konturer, Inkscape:
    Path → Object to Path) om tryckeriet saknar Inter.
  -->
  <g id="varumaerke" transform="translate(0 0) scale(0.46875)">${iconPaths}
  </g>
  <g id="ordmark" font-family="Inter, 'Segoe UI', Arial, sans-serif">
    <text id="namn" x="272" y="150" font-size="64" font-weight="800" fill="#0b2239">Dokumentportalen</text>
    <text id="foretag" x="274" y="200" font-size="24" font-weight="800" letter-spacing="7" fill="#0f9b8e">TADGA AB</text>
  </g>
</svg>
`;
const printTarget = path.join(root, 'assets/tadega-logo-tryck.svg');
fs.writeFileSync(printTarget, printSvg);
console.log(`assets/tadega-logo-tryck.svg written (editable print original)`);
