'use strict';
// Regenerate assets/tadega-logo.svg (outlined wordmark for screen) and
// assets/tadega-logo-tryck.svg (editable print original with live text).
// The badge is drawn as vector shapes; "Dokumentportalen" and "TADGA AB" are
// converted to outlines with opentype.js in the screen logo so print output
// can never substitute a font, while the print SVG keeps them as text objects.
// Run: node tools/build-logo.js
const fs = require('node:fs');
const path = require('node:path');
const opentype = require('opentype.js');

const root = path.resolve(__dirname, '..');
const fontPath = path.join(
    root,
    'node_modules/@expo-google-fonts/inter/800ExtraBold/Inter_800ExtraBold.ttf'
);
const font = (() => {
    const buffer = fs.readFileSync(fontPath);
    return opentype.parse(buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength));
})();

const scaleOf = (fontSize) => fontSize / font.unitsPerEm;

/** Lay a string out glyph by glyph (with kerning and optional tracking). */
function outline(text, fontSize, x, y, tracking = 0) {
    const scale = scaleOf(fontSize);
    let penX = x;
    let pathData = '';
    let previous = null;
    for (const character of text) {
        const glyph = font.charToGlyph(character);
        if (previous) {
            penX += font.getKerningValue(previous, glyph) * scale;
        }
        pathData += glyph.getPath(penX, y, fontSize).toPathData(2);
        penX += glyph.advanceWidth * scale + tracking;
        previous = glyph;
    }
    return { pathData, advance: Math.round(penX - x - tracking) };
}

