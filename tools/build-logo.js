'use strict';
// Regenerate assets/tadega-logo.svg with a font-independent wordmark.
// The badge is drawn as vector shapes and "Dokumentportalen" is converted
// to outlines with opentype.js, so print output can never substitute a font.
// Run: node tools/build-logo.js
const fs = require('node:fs');
const path = require('node:path');
const opentype = require('opentype.js');

const root = path.resolve(__dirname, '..');
const fontPath = path.join(
    root,
    'node_modules/@expo-google-fonts/inter/800ExtraBold/Inter_800ExtraBold.ttf'
);
const font = (() => {
    const buffer = fs.readFileSync(fontPath);
    return opentype.parse(buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength));
})();

const text = 'Dokumentportalen';
const fontSize = 64;
const x = 272;
const y = 150;
// Lay the word out glyph by glyph (with kerning) instead of running the
// full shaping pipeline: Inter's GSUB features are not needed for a fixed
// logo string and opentype.js cannot apply all of them.
const scale = fontSize / font.unitsPerEm;
let penX = x;
let pathData = '';
let previous = null;
for (const character of text) {
    const glyph = font.charToGlyph(character);
    if (previous) {
        penX += font.getKerningValue(previous, glyph) * scale;
    }
    pathData += glyph.getPath(penX, y, fontSize).toPathData(2);
    penX += glyph.advanceWidth * scale;
    previous = glyph;
}
const advance = Math.round(penX - x);
if (x + advance > 960) {
    throw new Error(`Wordmark overflows the viewBox (ends at ${x + advance})`);
}

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 240" role="img" aria-label="Dokumentportalen">
  <!--
    Editable vector logo for screen and print, generated by tools/build-logo.js.
    The wordmark is outlined paths (Inter ExtraBold) so no font is required
    at the print shop; edit wording/type only by rerunning the build script.
  -->
  <!-- Flat fills only: portal_sanitize_svg strips defs/gradients on view. -->
  <g transform="translate(0 0) scale(0.46875)">
    <rect width="512" height="512" rx="112" fill="#07172d"/>
    <path d="M56 400V316l48-50h288l44 40 10 12 30 16 14 14v52z" fill="#ffffff"/>
    <rect x="116" y="276" width="80" height="32" fill="#7fd6c8"/>
    <rect x="208" y="276" width="92" height="32" fill="#7fd6c8"/>
    <rect x="312" y="276" width="68" height="32" fill="#7fd6c8"/>
    <g stroke="#0f9b8e" stroke-width="3.5" stroke-linecap="round">
      <path d="M254 282v11"/>
      <path d="M248 286l6 5"/>
      <path d="M260 286l-6 5"/>
      <path d="M254 297v6"/>
    </g>
    <path d="M84 348h372" stroke="#0f9b8e" stroke-width="7" stroke-linecap="round"/>
    <circle cx="130" cy="400" r="44" fill="#07172d" stroke="#ffffff" stroke-width="10"/>
    <circle cx="420" cy="400" r="44" fill="#07172d" stroke="#ffffff" stroke-width="10"/>
    <circle cx="130" cy="400" r="10" fill="#ffffff"/>
    <circle cx="420" cy="400" r="10" fill="#ffffff"/>
  </g>
  <path d="${pathData}" fill="#0b2239"/>
  <rect x="${x}" y="176" width="${advance}" height="8" rx="4" fill="#0f9b8e"/>
</svg>
`;

const target = path.join(root, 'assets/tadega-logo.svg');
fs.writeFileSync(target, svg);
console.log(`assets/tadega-logo.svg written (wordmark width ${advance}px, ends at ${x + advance}px)`);
